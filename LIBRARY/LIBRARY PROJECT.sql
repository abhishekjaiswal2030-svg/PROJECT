-- 20 Remaining stock after all orders:

SELECT b.BOOK_ID, b.TITLE, b.STOCK AS INITIAL_STOCK,
COALESCE(SUM(o.QUANTITY), 0) AS TOTAL_ORDERED,
(b.STOCK - COALESCE(SUM(o.QUANTITY), 0)) AS REMAINING_STOCK
FROM BOOKS b
LEFT JOIN ORDERS o ON b.BOOKS_ID = o.BOOK_ID
GROUP BY b.BOOK_ID, b.TITLE, b.STOCK;

-- Har Payment_Method ke kitne customers hain, aur unhone total kitna revenue diya:

SELECT PAYMENT_METHOD, SUM(TOTAL_AMOUNT) AS REVENUE FROM ORDERS JOIN 
CUSTOMERS ON ORDERS.CUSTOMER_ID=CUSTOMERS.CUSTOMER_ID GROUP BY PAYMENT_METHOD; 

-- Kaunsa Platform sabse zyada orders aur sabse zyada quantity de raha hai? Uska total revenue mein % share bhi nikalo.

SELECT PLATFORM, SUM(QUANTITY) AS QUANTITY,SUM(ORDER_ID) AS ORDERS
, SUM(TOTAL_AMOUNT) AS REVENUE,
ROUND((SUM(TOTAL_AMOUNT) * 100.0) / (SELECT SUM(TOTAL_AMOUNT)
 FROM ORDERS),2)
 AS REVENUE_PERCENTAGE_SHARE FROM ORDERS JOIN 
CUSTOMERS ON ORDERS.CUSTOMER_ID=CUSTOMERS.CUSTOMER_ID GROUP BY PLATFORM ; 

--  Platform aur Payment_Method ke har combination ka average order value nikalo, aur top 3 combinations dikhao.

SELECT 
    PLATFORM,
    PAYMENT_METHOD,
    ROUND(AVG(TOTAL_AMOUNT), 2) AS AVG_ORDER_VALUE,
    COUNT(ORDER_ID) AS TOTAL_ORDERS
FROM CUSTOMERS JOIN ORDERS ON CUSTOMERS.CUSTOMER_ID = ORDERS.CUSTOMER_ID
GROUP BY CUSTOMERS .PLATFORM, CUSTOMERS.PAYMENT_METHOD
ORDER BY AVG_ORDER_VALUE DESC
LIMIT 3;